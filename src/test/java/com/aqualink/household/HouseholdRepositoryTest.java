    @Autowired
    private HouseholdRepository households;

        @Autowired
        private CommunityRepository communities;

    @Autowired
    private UserRepository users;

        @Autowired
        private WaterOrderRepository orders;

        @Autowired
        private PooledOrderMemberRepository pooledMembers;

        @Autowired
        private WaterProviderRepository waterProviders;

    @Autowired
    private JdbcTemplate jdbc;

